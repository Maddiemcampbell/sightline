import {
  AdminPageHeader,
  EmptyTable,
  formatDateTime,
  MetricCards,
  StatusPill,
} from "@/features/platform-admin/data-ui";
import { requirePlatformPermission } from "@/features/platform-admin/authorization";
import { PlatformOperationsService } from "@/features/platform-admin/services";
import { createAdminSupabaseClient } from "@/lib/supabase/server";

export const dynamic = "force-dynamic";

export default async function PlatformSystemHealthPage() {
  await requirePlatformPermission(
    "platform.health.read",
    "admin_page",
    "system_health",
  );
  const client = createAdminSupabaseClient();
  const service = new PlatformOperationsService(client);
  const [metrics, alerts] = await Promise.all([
    service.healthSummary(),
    client
      .from("job_monitoring_alerts")
      .select("*")
      .order("last_detected_at", { ascending: false })
      .limit(20),
  ]);
  if (alerts.error) throw new Error(alerts.error.message);
  return (
    <div className="space-y-6 p-6">
      <AdminPageHeader
        eyebrow="Operations"
        title="System health"
        description="Live dependency checks and centralized background-job alerts. Health is measured from safe service queries and recent durable records."
      />
      <MetricCards metrics={metrics} />
      <section className="overflow-hidden rounded-lg border bg-white">
        <div className="border-b p-4">
          <h2 className="font-semibold">Recent job alerts</h2>
          <p className="mt-1 text-xs text-slate-500">
            Open and recovered alerts generated by centralized monitoring.
          </p>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full min-w-[55rem] text-left text-sm">
            <thead className="border-b bg-slate-50 text-xs text-slate-500 uppercase">
              <tr>
                <th className="p-3">Alert</th>
                <th className="p-3">Status</th>
                <th className="p-3">Severity</th>
                <th className="p-3">Occurrences</th>
                <th className="p-3">Last detected</th>
              </tr>
            </thead>
            <tbody>
              {(alerts.data ?? []).map((alert) => (
                <tr key={alert.id} className="border-b last:border-0">
                  <td className="p-3">
                    <p className="font-semibold">{alert.summary}</p>
                    <p className="mt-1 text-xs text-slate-500">
                      {alert.job_type.replaceAll("_", " ")} ·{" "}
                      {alert.alert_type.replaceAll("_", " ")}
                    </p>
                  </td>
                  <td className="p-3">
                    <StatusPill value={alert.status} />
                  </td>
                  <td className="p-3">
                    <StatusPill value={alert.severity} />
                  </td>
                  <td className="p-3">{alert.occurrence_count}</td>
                  <td className="p-3">
                    {formatDateTime(alert.last_detected_at)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        {!alerts.data?.length ? (
          <EmptyTable>No job alerts have been recorded.</EmptyTable>
        ) : null}
      </section>
    </div>
  );
}
